<?php

namespace App\Support;

use BackedEnum;
use Illuminate\Support\Facades\File;
use ReflectionEnum;

/**
 * Renders every backed enum in app/Enums as TypeScript (CLAUDE.md: generate
 * matching TS types; don't hand-write duplicates).
 */
class EnumTypeScriptGenerator
{
    public const OUTPUT_PATH = 'resources/js/types/enums.ts';

    /**
     * @return list<class-string<BackedEnum>>
     */
    public function enums(): array
    {
        $classes = [];

        foreach (File::files(app_path('Enums')) as $file) {
            $class = 'App\\Enums\\'.$file->getFilenameWithoutExtension();

            if (enum_exists($class) && is_subclass_of($class, BackedEnum::class)) {
                $classes[] = $class;
            }
        }

        sort($classes);

        return $classes;
    }

    public function generate(): string
    {
        $out = "// Generated by `php artisan gm:types` from app/Enums. Do not edit by hand.\n";

        foreach ($this->enums() as $class) {
            $out .= "\n".$this->renderEnum($class);
        }

        return $out;
    }

    /**
     * @param  class-string<BackedEnum>  $class
     */
    private function renderEnum(string $class): string
    {
        $name = (new ReflectionEnum($class))->getShortName();
        $isInt = (string) (new ReflectionEnum($class))->getBackingType() === 'int';

        $members = '';
        $labels = '';

        foreach ($class::cases() as $case) {
            $value = $isInt ? (string) $case->value : $this->quote((string) $case->value);
            $label = method_exists($case, 'label') ? $case->label() : $case->name;
            $members .= "    {$case->name}: {$value},\n";
            $labels .= "    {$value}: {$this->quote($label)},\n";
        }

        return "export const {$name} = {\n{$members}} as const;\n"
            ."export type {$name} = (typeof {$name})[keyof typeof {$name}];\n"
            ."export const {$name}Labels: Record<{$name}, string> = {\n{$labels}};\n";
    }

    private function quote(string $value): string
    {
        return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
    }
}
